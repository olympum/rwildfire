// Pinned Java operation order is intentional: the lookup values come from
// JDK 8 StrictMath, and the derivative sums below must round exactly as
// FastMathLibImpl.tan does, so do not refactor them into mul_add or fma.

// TAN_VIRTUAL_TABS_SIZE = (1 << 12) + 1: one half-pi period in 4096 intervals.
const VIRTUAL_SIZE: usize = 4097;
// TAN_TABS_SIZE = (int) (toRadians(77) / (pi / 2) * 4096) + 1.
const TABS_SIZE: usize = 3505;

// TAN_DELTA_HI/LO and TAN_INDEXER are FastMathLibImpl.PIO2_HI/PIO2_LO
// divided by 4096; PIO2 is split so that HI + LO rounds to pi / 2.
const DELTA_HI: f64 = f64::from_bits(0x3f39_21fb_5440_0000);
const DELTA_LO: f64 = f64::from_bits(0x3d10_b461_1a62_6331);
const INDEXER: f64 = f64::from_bits(0x40a4_5f30_6dc9_c883);

// TAN_MAX_VALUE_FOR_INT_MODULO = 4194303.0 / TAN_INDEXER * 0.99.
// At or below this magnitude the masked integer index stays in the virtual
// table. Above it FastMathLibImpl reduces modulo 2*pi first.
const MAX_VALUE_FOR_INT_MODULO: f64 = f64::from_bits(0x4098_e1a3_f275_3f24);

const HALF_PI: f64 = f64::from_bits(0x3ff9_21fb_5444_2d18);
const PI: f64 = f64::from_bits(0x4009_21fb_5444_2d18);

// (tan(x), tan'(x)/1!, tan''(x)/2!, tan'''(x)/3!, tan''''(x)/4!)
// for x = i * DELTA_HI + i * DELTA_LO, generated by oracle/StrictTanTable.java
// on Temurin 8. Values are stored as raw bits so no decimal round-trip occurs.
static TABLE: [(u64, u64, u64, u64, u64); TABS_SIZE] = include!("strict_tan_table.in");

pub(crate) fn tan(angle: f64) -> f64 {
    let mut angle = angle;

    // FastMathLibImpl.tan's large-angle path. remainder_two_pi is the shared
    // exact port of FastMathLibImpl.remainderTwoPi, in crate::angle_reduce.
    if angle.abs() > MAX_VALUE_FOR_INT_MODULO {
        angle = crate::angle_reduce::remainder_two_pi(angle);
        if angle < -HALF_PI {
            angle += PI;
        } else if angle > HALF_PI {
            angle -= PI;
        }
    }

    let negative = angle < 0.0;
    if negative {
        angle = -angle;
    }

    // Compute the index before masking: the fractional delta must use the
    // unmasked index, exactly as in the Java source.
    let raw_index = (angle * INDEXER + 0.5) as usize;
    let mut delta = angle - (raw_index as f64) * DELTA_HI - (raw_index as f64) * DELTA_LO;
    let mut index = raw_index & (2 * (VIRTUAL_SIZE - 1) - 1);
    let mut negative = negative;

    // Fold the second quarter of the virtual table back onto the first.
    if index > VIRTUAL_SIZE - 1 {
        index = 2 * (VIRTUAL_SIZE - 1) - index;
        delta = -delta;
        negative = !negative;
    }

    let result = if index < TABS_SIZE {
        let (tan, d1, d2, d3, d4) = TABLE[index];
        let tan = f64::from_bits(tan);
        let d1 = f64::from_bits(d1);
        let d2 = f64::from_bits(d2);
        let d3 = f64::from_bits(d3);
        let d4 = f64::from_bits(d4);
        tan + delta * (d1 + delta * (d2 + delta * (d3 + delta * d4)))
    } else {
        // Near pi / 2 the table stores the cotangent form, so invert the
        // residual sum with alternating signs.
        let index = VIRTUAL_SIZE - 1 - index;
        let (tan, d1, d2, d3, d4) = TABLE[index];
        let tan = f64::from_bits(tan);
        let d1 = f64::from_bits(d1);
        let d2 = f64::from_bits(d2);
        let d3 = f64::from_bits(d3);
        let d4 = f64::from_bits(d4);
        1.0 / (tan - delta * (d1 - delta * (d2 - delta * (d3 - delta * d4))))
    };

    if negative {
        -result
    } else {
        result
    }
}
